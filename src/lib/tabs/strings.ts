const TABS: Partial<Record<Lang, Record<TabKey, string>>> = { en: TABS_EN, ta: TABS_TA, hi: TABS_HI };

/** Translate a tab string and fill in {placeholders}. Falls back to English. */
export function tt(lang: Lang, key: TabKey, vars: Record<string, string | number> = {}): string {
  const template = TABS[lang]?.[key] ?? TABS_EN[key];
  return template.replace(/\{(\w+)\}/g, (_, name: string) => (name in vars ? String(vars[name]) : `{${name}}`));
}
