export function careT(lang: Lang, key: CareKey, vars: Record<string, string | number> = {}): string {
  const template = CARE[lang]?.[key] ?? CARE_EN[key];
  return template.replace(/\{(\w+)\}/g, (_, name: string) => (name in vars ? String(vars[name]) : `{${name}}`));
}
